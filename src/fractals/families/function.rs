// 102. De Rham Curve
pub struct DeRhamCurve;
impl Fractal for DeRhamCurve {
    fn id(&self) -> &'static str { "de-rham-curve" }
    fn name(&self) -> &'static str { "De Rham Curve" }
    fn family(&self) -> &'static str { "function-family" }
    fn formula(&self) -> &'static str { "Georges de Rham's continuous nowhere-differentiable affine curve" }
    fn description(&self) -> &'static str { "Nowhere-differentiable fractal curve generated by binary contraction maps." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.5, 1.2) }

    fn compute(&self, x: f64, y: f64, _config: &FractalConfig) -> Option<f64> {
        let mut u = (x + 1.0) * 0.5;
        let mut val = 0.0;
        let mut scale = 1.0;
        for _ in 0..16 {
            let bit = (u * 2.0).floor() as i64;
            val += (if bit == 1 { 0.7 } else { 0.3 }) * scale;
            scale *= 0.5;
            u = (u * 2.0).fract();
        }
        let d = (y - (val * 2.0 - 1.0)).abs();
        if d < 0.08 {
            Some((1.0 - d / 0.08).clamp(0.0, 1.0))
        } else {
            None
        }
    }
}

// 103. Weierstrass Function
pub struct WeierstrassFunction;
impl Fractal for WeierstrassFunction {
    fn id(&self) -> &'static str { "weierstrass" }
    fn name(&self) -> &'static str { "Weierstrass Function" }
    fn family(&self) -> &'static str { "function-family" }
    fn formula(&self) -> &'static str { "f(x) = Σ a^n * cos(b^n * π * x), ab > 1 + 3π/2" }
    fn description(&self) -> &'static str { "Karl Weierstrass's famous 1872 continuous nowhere-differentiable pathological monster." }
    fn bounds(&self) -> InterestingBounds {
        InterestingBounds {
            min_offset_x: -2.0, max_offset_x: 2.0,
            min_offset_y: -2.5, max_offset_y: 2.5,
            default_offset_x: 0.0, default_offset_y: 0.0,
            default_zoom: 1.0,
            ..InterestingBounds::default()
        }
    }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let a = 0.5f64;
        let b = 3.0f64;
        let mut sum = 0.0;
        let max_n = config.iterations.min(24);

        for n in 0..max_n {
            let an = a.powi(n as i32);
            let bn = b.powi(n as i32);
            sum += an * (bn * std::f64::consts::PI * x).cos();
        }

        let d = (y - sum).abs();
        let thickness = 0.06;
        if d < thickness {
            Some((1.0 - d / thickness).clamp(0.0, 1.0))
        } else {
            None
        }
    }
}

// 104. Takagi Function
pub struct TakagiFunction;
impl Fractal for TakagiFunction {
    fn id(&self) -> &'static str { "takagi" }
    fn name(&self) -> &'static str { "Takagi Function" }
    fn family(&self) -> &'static str { "function-family" }
    fn formula(&self) -> &'static str { "T(x) = Σ 2^(-n) * dist(2^n * x, Z)" }
    fn description(&self) -> &'static str { "Teiji Takagi's simple continuous nowhere-differentiable sawtooth sum." }
    fn bounds(&self) -> InterestingBounds {
        InterestingBounds {
            min_offset_x: -0.2, max_offset_x: 1.2,
            min_offset_y: -0.2, max_offset_y: 1.2,
            default_offset_x: 0.5, default_offset_y: 0.5,
            default_zoom: 1.5,
            ..InterestingBounds::default()
        }
    }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let mut sum = 0.0;
        let mut pow2 = 1.0;
        let max_n = config.iterations.min(20);

        for _ in 0..max_n {
            let val = x * pow2;
            let dist = (val - val.round()).abs();
            sum += dist / pow2;
            pow2 *= 2.0;
        }

        let d = (y - sum).abs();
        let thickness = 0.04;
        if d < thickness {
            Some((1.0 - d / thickness).clamp(0.0, 1.0))
        } else {
            None
        }
    }
}

// 105. Blancmange Curve
pub struct BlancmangeCurve;
impl Fractal for BlancmangeCurve {
    fn id(&self) -> &'static str { "blancmange" }
    fn name(&self) -> &'static str { "Blancmange Curve" }
    fn family(&self) -> &'static str { "function-family" }
    fn formula(&self) -> &'static str { "B(x) = Σ s(2^n * x) / 2^n with triangular wave s(x)" }
    fn description(&self) -> &'static str { "The blancmange curve resembling a scalloped French pudding dessert." }
    fn bounds(&self) -> InterestingBounds {
        InterestingBounds {
            default_offset_x: 0.5, default_offset_y: 0.5,
            ..InterestingBounds::centered(1.2, 1.5)
        }
    }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let takagi = TakagiFunction;
        takagi.compute(x, y, config)
    }
}
