// 60. Fractal Islands
pub struct FractalIslands;
impl Fractal for FractalIslands {
    fn id(&self) -> &'static str { "fractal-islands" }
    fn name(&self) -> &'static str { "Fractal Islands" }
    fn family(&self) -> &'static str { "koch-family" }
    fn formula(&self) -> &'static str { "Koch-style coastline boundary deformation" }
    fn description(&self) -> &'static str { "Fractal islands with realistic craggy coastlines generated by Koch recursions." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.5, 1.2) }

    fn compute(&self, x: f64, y: f64, _config: &FractalConfig) -> Option<f64> {
        let r = (x * x + y * y).sqrt();
        let theta = y.atan2(x);
        let mut boundary = 0.8;
        let mut freq = 3.0;
        let mut amp = 0.25;
        for _ in 0..6 {
            boundary += amp * (freq * theta).sin();
            freq *= 3.0;
            amp *= 0.5;
        }
        if r < boundary {
            Some(r / boundary)
        } else {
            None
        }
    }
}

// 61. Koch Snowflake
pub struct KochSnowflake;
impl Fractal for KochSnowflake {
    fn id(&self) -> &'static str { "koch" }
    fn name(&self) -> &'static str { "Koch Snowflake" }
    fn family(&self) -> &'static str { "koch-family" }
    fn formula(&self) -> &'static str { "Equilateral middle-third triangular replacement: D = log(4)/log(3) ≈ 1.262" }
    fn description(&self) -> &'static str { "Helge von Koch's celebrated snowflake curve with infinite perimeter." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.5, 1.2) }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let mut px = x.abs();
        let mut py = y;
        let max_iter = config.iterations.min(16);

        // Fold equilateral symmetry
        let sqrt3 = 3.0f64.sqrt();
        for i in 0..max_iter {
            if px * sqrt3 + py > 1.0 {
                let d = (px * sqrt3 + py - 1.0) * 0.5;
                px -= d * sqrt3;
                py -= d;
            }
            px = px.abs();
            px = (px * 3.0) - 1.0;
            py = (py * 3.0) - 1.0;
            if px * px + py * py > 6.0 {
                return Some(i as f64 / max_iter as f64);
            }
        }
        None
    }
}

// 62. Quadratic Koch
pub struct QuadraticKoch;
impl Fractal for QuadraticKoch {
    fn id(&self) -> &'static str { "quadratic-koch" }
    fn name(&self) -> &'static str { "Quadratic Koch" }
    fn family(&self) -> &'static str { "koch-family" }
    fn formula(&self) -> &'static str { "Square pulse replacement: D = log(8)/log(4) = 1.5" }
    fn description(&self) -> &'static str { "Minkowski / quadratic Koch island using right-angled square protrusions." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.5, 1.2) }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let mut px = x.abs();
        let mut py = y.abs();
        let max_iter = config.iterations.min(16);

        for i in 0..max_iter {
            if px > 1.0 || py > 1.0 { return Some(i as f64 / max_iter as f64); }
            px *= 4.0;
            py *= 4.0;
            let ipx = (px.floor() as i64) % 4;
            let ipy = (py.floor() as i64) % 4;
            if (ipx == 1 || ipx == 2) && (ipy == 1 || ipy == 2) {
                return Some(i as f64 / max_iter as f64);
            }
            px -= px.floor();
            py -= py.floor();
        }
        None
    }
}
