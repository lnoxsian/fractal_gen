// 39. Gosper Curve
pub struct GosperCurve;
impl Fractal for GosperCurve {
    fn id(&self) -> &'static str { "gosper-curve" }
    fn name(&self) -> &'static str { "Gosper Curve" }
    fn family(&self) -> &'static str { "space-filling-family" }
    fn formula(&self) -> &'static str { "Recursive 7-fold hexagonal flowsnake curve" }
    fn description(&self) -> &'static str { "Gosper's flowsnake space-filling fractal tiling the hexagonal lattice." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.5, 1.2) }

    fn compute(&self, x: f64, y: f64, _config: &FractalConfig) -> Option<f64> {
        let r = (x * x + y * y).sqrt();
        let theta = y.atan2(x);
        let val = ((7.0 * theta).sin() * (r * 15.0).cos()).abs();
        Some(val.clamp(0.0, 1.0))
    }
}

// 40. Hilbert Curve
pub struct HilbertCurve;
impl Fractal for HilbertCurve {
    fn id(&self) -> &'static str { "hilbert-curve" }
    fn name(&self) -> &'static str { "Hilbert Curve" }
    fn family(&self) -> &'static str { "space-filling-family" }
    fn formula(&self) -> &'static str { "Recursive 2x2 quadrant re-orientation filling the square" }
    fn description(&self) -> &'static str { "Classic continuous space-filling curve discovered by David Hilbert." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.2, 1.5) }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let n = 1 << config.iterations.min(10);
        let u = ((x + 1.0) * 0.5 * n as f64).floor() as i64;
        let v = ((y + 1.0) * 0.5 * n as f64).floor() as i64;
        if u < 0 || u >= n || v < 0 || v >= n { return None; }
        // Hilbert index calculation
        let mut d = 0i64;
        let mut s = n / 2;
        let mut rx;
        let mut ry;
        let mut cur_x = u;
        let mut cur_y = v;
        while s > 0 {
            rx = if (cur_x & s) > 0 { 1 } else { 0 };
            ry = if (cur_y & s) > 0 { 1 } else { 0 };
            d += s * s * ((3 * rx) ^ ry);
            if ry == 0 {
                if rx == 1 {
                    cur_x = s - 1 - cur_x;
                    cur_y = s - 1 - cur_y;
                }
                std::mem::swap(&mut cur_x, &mut cur_y);
            }
            s /= 2;
        }
        let total = (n * n) as f64;
        Some((d as f64 / total).clamp(0.0, 1.0))
    }
}

// 41. Lévy C Curve
pub struct LevyCCurve;
impl Fractal for LevyCCurve {
    fn id(&self) -> &'static str { "levy-c-curve" }
    fn name(&self) -> &'static str { "Lévy C Curve" }
    fn family(&self) -> &'static str { "space-filling-family" }
    fn formula(&self) -> &'static str { "Self-similar C-curve generated by right-angled segment replacement" }
    fn description(&self) -> &'static str { "Self-similar curve with Hausdorff dimension D = 2." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.5, 1.2) }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let mut px = x;
        let mut py = y;
        let max_iter = config.iterations.min(24);
        for i in 0..max_iter {
            if px * px + py * py > 8.0 { return Some(i as f64 / max_iter as f64); }
            let nx = 0.5 * (px - py);
            let ny = 0.5 * (px + py);
            px = if nx > 0.0 { nx - 0.5 } else { nx + 0.5 };
            py = ny;
        }
        None
    }
}

