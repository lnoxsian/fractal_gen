// 43. Peano Curve
pub struct PeanoCurve;
impl Fractal for PeanoCurve {
    fn id(&self) -> &'static str { "peano-curve" }
    fn name(&self) -> &'static str { "Peano Curve" }
    fn family(&self) -> &'static str { "space-filling-family" }
    fn formula(&self) -> &'static str { "First continuous space-filling curve based on 3x3 subdivision" }
    fn description(&self) -> &'static str { "The historical original 1890 space-filling curve discovered by Giuseppe Peano." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.2, 1.5) }

    fn compute(&self, x: f64, y: f64, config: &FractalConfig) -> Option<f64> {
        let mut u = (x + 1.0) * 0.5;
        let mut v = (y + 1.0) * 0.5;
        if u < 0.0 || u > 1.0 || v < 0.0 || v > 1.0 { return None; }
        let mut code = 0i64;
        let max_iter = config.iterations.min(10);
        for _ in 0..max_iter {
            u *= 3.0;
            v *= 3.0;
            let iu = (u.floor() as i64) % 3;
            let iv = (v.floor() as i64) % 3;
            code = code * 9 + (iu * 3 + iv);
            u -= u.floor();
            v -= v.floor();
        }
        let max_code = 9f64.powi(max_iter as i32);
        Some((code as f64 / max_code).clamp(0.0, 1.0))
    }
}

// 44. Sierpinski Curve
pub struct SierpinskiCurve;
impl Fractal for SierpinskiCurve {
    fn id(&self) -> &'static str { "sierpinski-curve" }
    fn name(&self) -> &'static str { "Sierpinski Curve" }
    fn family(&self) -> &'static str { "space-filling-family" }
    fn formula(&self) -> &'static str { "Continuous closed space-filling path around Sierpinski triangle boundaries" }
    fn description(&self) -> &'static str { "Continuous closed curve wrapping the perimeter of Sierpinski triangle iterations." }
    fn bounds(&self) -> InterestingBounds { InterestingBounds::centered(1.5, 1.2) }

    fn compute(&self, x: f64, y: f64, _config: &FractalConfig) -> Option<f64> {
        let ix = ((x + 1.0) * 256.0) as i64;
        let iy = ((y + 1.0) * 256.0) as i64;
        let val = ((ix + iy) ^ (ix - iy)).abs() % 256;
        Some(val as f64 / 255.0)
    }
}
