impl fmt::Display for ColorScheme {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.identifier())
    }
}

impl FromStr for ColorScheme {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let clean = s.trim().to_ascii_lowercase().replace('_', "-");
        for &scheme in &Self::ALL {
            if scheme.identifier() == clean {
                return Ok(scheme);
            }
        }
        // Also allow indexing by integer 0..47
        if let Ok(idx) = clean.parse::<usize>() {
            if idx < Self::ALL.len() {
                return Ok(Self::ALL[idx]);
            }
        }
        Err(format!("Unknown color scheme: '{s}'. Valid schemes: classic, fire, ocean, rainbow, cosmic, etc. (0-47)"))
    }
}
